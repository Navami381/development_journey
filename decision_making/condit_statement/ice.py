"""
**Ice Cream Flavors**
   - Input (1-4): Choose from 1 (Chocolate), 2 (Vanilla), 3 (Strawberry), 4 (Butterscotch).
"""
input=int(input("enter input..."))

if input==1:
    print("chocolate")
elif input==2:
    print("vanilla")
elif input==3:
    print("strawberry")
elif input==4:
    print("butterscotch")
else:
    print("invalid choice")